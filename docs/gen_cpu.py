#!/usr/bin/env python3
"""Generates lib/cpu.a: the machine code of the asm blocks is assembled with llvm-mc (the A compiler contains no
assembler), so every instruction word in lib/cpu.a is checked by an independent tool.   usage: docs/gen_cpu.py"""
import os

import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from asmgen import *

OPS = {}
OPS['cycles'] = {
 'x64': 'rdtsc\nshlq $32, %rdx\norq %rdx, %rax',
 'arm64': 'mrs x0, cntvct_el0',
 'riscv64': 'rdtime a0',
 'loongarch64': 'rdtime.d $a0, $zero'}
OPS['pause'] = {'x64': 'pause', 'arm64': 'yield', 'riscv64': 'pause', 'loongarch64': 'nop'}
OPS['fence'] = {'x64': 'mfence', 'arm64': 'dmb ish', 'riscv64': 'fence rw, rw', 'loongarch64': 'dbar 0'}
OPS['add'] = {
 'x64': 'lock xaddq %rcx, (%rax)\nmovq %rcx, %rax',
 'arm64': 'mov x3, x0\n1:\nldaxr x0, [x3]\nadd x4, x0, x1\nstlxr w5, x4, [x3]\ncbnz w5, 1b\ndmb ish',
 'riscv64': 'amoadd.d.aqrl a2, a1, (a0)\nmv a0, a2',
 'loongarch64': 'amadd_db.d $a2, $a1, $a0\nmove $a0, $a2'}
OPS['swap'] = {
 'x64': 'xchgq %rcx, (%rax)\nmovq %rcx, %rax',
 'arm64': 'mov x3, x0\n1:\nldaxr x0, [x3]\nstlxr w5, x1, [x3]\ncbnz w5, 1b\ndmb ish',
 'riscv64': 'amoswap.d.aqrl a2, a1, (a0)\nmv a0, a2',
 'loongarch64': 'amswap_db.d $a2, $a1, $a0\nmove $a0, $a2'}
OPS['cas'] = {
 'x64': 'movq %rax, %rsi\nmovq %rcx, %rax\nlock cmpxchgq %rdx, (%rsi)',
 'arm64': 'mov x3, x0\n1:\nldaxr x0, [x3]\ncmp x0, x1\nb.ne 2f\nstlxr w5, x2, [x3]\ncbnz w5, 1b\n2:\ndmb ish',
 'riscv64': 'mv t3, a0\n1:\nlr.d.aqrl t0, (t3)\nbne t0, a1, 2f\nsc.d.rl t1, a2, (t3)\nbnez t1, 1b\n2:\nmv a0, t0',
 'loongarch64': 'move $t3, $a0\n1:\nll.d $t0, $t3, 0\nbne $t0, $a1, 2f\nmove $t1, $a2\nsc.d $t1, $t3, 0\nbeqz $t1, 1b\n2:\ndbar 0\nmove $a0, $t0'}
OPS['load'] = {
 'x64': 'movq (%rax), %rax',
 'arm64': 'ldar x0, [x0]',
 'riscv64': 'ld a0, 0(a0)\nfence r, rw',
 'loongarch64': 'ld.d $a0, $a0, 0\ndbar 0'}
OPS['store'] = {
 'x64': 'xchgq %rcx, (%rax)',
 'arm64': 'stlr x1, [x0]\ndmb ish',
 'riscv64': 'fence rw, w\nsd a1, 0(a0)\nfence rw, rw',
 'loongarch64': 'dbar 0\nst.d $a1, $a0, 0\ndbar 0'}
for reg, mov in (('eax', ''), ('ebx', 'movl %ebx, %eax'), ('ecx', 'movl %ecx, %eax'), ('edx', 'movl %edx, %eax')):
    OPS['cpuid_' + reg] = {
     'x64': 'pushq %rbx\ncpuid\n' + (mov + '\n' if mov else '') + 'popq %rbx',
     'arm64': 'mov x0, #0', 'riscv64': 'li a0, 0', 'loongarch64': 'li.d $a0, 0'}

blocks = {k: asm_block(v, {'cycles': '', 'pause': '', 'fence': '', 'add': 'p, v', 'swap': 'p, v', 'cas': 'p, expected, desired',
                            'load': 'p', 'store': 'p, v'}.get(k, 'leaf, sub')) for k, v in OPS.items()}

HEAD = open(os.path.join(os.path.dirname(__file__), 'cpu_head.a.txt')).read() if os.path.exists(os.path.join(os.path.dirname(__file__), 'cpu_head.a.txt')) else ''

src = '''// =============================================================================
//  cpu - the processor: timer, barriers, atomic operations, CPU identification        import cpu;
//
//  Built on the asm blocks of the language: machine code for x86-64, AArch64, RISC-V 64 and LoongArch64
//  (this file is generated by docs/gen_cpu.py, the code words come from llvm-mc).
//
//    cpu.cycles()                          a monotonic counter of the CPU (cycles on x86-64, the fixed rate timer elsewhere)
//    cpu.pause()  cpu.fence()              spin loop hint; full memory barrier
//    cpu.atomicAdd(&n, 1)                  adds, returns the OLD value        (also atomicSub, atomicInc, atomicDec)
//    cpu.atomicSwap(&n, v)                 stores v, returns the old value
//    cpu.atomicCas(&n, expected, desired)  stores desired if n == expected; returns the old value
//    cpu.atomicLoad(&n)  cpu.atomicStore(&n, v)
//    cpu.lock(&flag)  cpu.unlock(&flag)  cpu.tryLock(&flag)       a spin lock on an int
//    cpu.archName()  cpu.arch()            which CPU this program was built for
//    cpu.cpuid(leaf, sub, reg)             x86-64 only (0 elsewhere); reg 0 = eax, 1 = ebx, 2 = ecx, 3 = edx
//    cpu.vendor()  cpu.brand()             x86-64: "GenuineIntel" / "AuthenticAMD", the marketing name; other CPUs: ""
//    cpu.hwcap()  cpu.hwcap2()             Linux / Android: the capability bits the kernel reports (AT_HWCAP / AT_HWCAP2)
// =============================================================================
module cpu;

public const ARCH_X64 = 0;
public const ARCH_ARM64 = 1;
public const ARCH_RISCV64 = 2;
public const ARCH_LOONGARCH64 = 3;

public int cycles() {
    return ''' + blocks['cycles'] + ''';
}

public void pause() {
    ''' + blocks['pause'] + '''
}

public void fence() {
    ''' + blocks['fence'] + '''
}

// ---- atomic operations on 64 bit integers (they all act as full memory barriers) ---------------------------------------------------------------
public int atomicAdd(int* p, int v) {
    return ''' + blocks['add'] + ''';
}

public int atomicSub(int* p, int v) {
    return atomicAdd(p, -v);
}

public int atomicInc(int* p) {
    return atomicAdd(p, 1);
}

public int atomicDec(int* p) {
    return atomicAdd(p, -1);
}

public int atomicSwap(int* p, int v) {
    return ''' + blocks['swap'] + ''';
}

public int atomicCas(int* p, int expected, int desired) {
    return ''' + blocks['cas'] + ''';
}

public int atomicLoad(int* p) {
    return ''' + blocks['load'] + ''';
}

public void atomicStore(int* p, int v) {
    ''' + blocks['store'] + '''
}

// ---- a spin lock: the int is 0 when free ---------------------------------------------------------------------------------------------------
public bool tryLock(int* flag) {
    return atomicCas(flag, 0, 1) == 0;
}

public void lock(int* flag) {
    while (atomicCas(flag, 0, 1) != 0) {
        pause();
    }
}

public void unlock(int* flag) {
    atomicStore(flag, 0);
}

// ---- which CPU --------------------------------------------------------------------------------------------------------------------------------
public int arch() {
    return __ARCH;
}

public char* archName() {
    if (__ARCH == 0) return "x86-64";
    if (__ARCH == 1) return "arm64";
    if (__ARCH == 2) return "riscv64";
    return "loongarch64";
}

// x86-64 CPUID: the register `reg` (0 eax, 1 ebx, 2 ecx, 3 edx) for the given leaf and sub leaf; 0 on other CPUs
public int cpuid(int leaf, int sub, int reg) {
    if (reg == 0) {
        return ''' + blocks['cpuid_eax'] + ''';
    }
    if (reg == 1) {
        return ''' + blocks['cpuid_ebx'] + ''';
    }
    if (reg == 2) {
        return ''' + blocks['cpuid_ecx'] + ''';
    }
    return ''' + blocks['cpuid_edx'] + ''';
}

private void put4(char* out, int o, int v) {
    out[o] = v & 255;
    out[o + 1] = (v >> 8) & 255;
    out[o + 2] = (v >> 16) & 255;
    out[o + 3] = (v >> 24) & 255;
}

// "GenuineIntel", "AuthenticAMD" ... (x86-64), "" on other CPUs
public char* vendor() {
    char* out = alloc(16);
    if (__ARCH != 0) {
        return out;
    }
    put4(out, 0, cpuid(0, 0, 1));
    put4(out, 4, cpuid(0, 0, 3));
    put4(out, 8, cpuid(0, 0, 2));
    return out;
}

// the processor's name as the manufacturer wrote it (x86-64), "" on other CPUs
public char* brand() {
    char* out = alloc(64);
    if (__ARCH != 0 || cpuid(0x80000000, 0, 0) < 0x80000004) {
        return out;
    }
    for (int i = 0; i < 3; i++) {
        int leaf = 0x80000002 + i;
        put4(out, i * 16, cpuid(leaf, 0, 0));
        put4(out, i * 16 + 4, cpuid(leaf, 0, 1));
        put4(out, i * 16 + 8, cpuid(leaf, 0, 2));
        put4(out, i * 16 + 12, cpuid(leaf, 0, 3));
    }
    // leading blanks
    int skip = 0;
    while (out[skip] == ' ') {
        skip++;
    }
    return &out[skip];
}

// an entry of the auxiliary vector the kernel gave the program (/proc/self/auxv): AT_HWCAP = 16, AT_HWCAP2 = 26.
// The bits are CPU specific: on RISC-V bit n is the extension letter n ('I', 'M', 'A', 'F', 'D', 'C' ...), on AArch64 see
// the kernel's hwcap.h. 0 when unknown (Windows).
private int auxv(int key) {
    if (__OS == 1) {
        return 0;
    }
    int h = fileOpen("/proc/self/auxv", FILE_READ);
    if (h < 0) {
        return 0;
    }
    int ent[2];
    int result = 0;
    while (fileRead(h, &ent[0], 16) == 16) {
        if (ent[0] == key) {
            result = ent[1];
            break;
        }
        if (ent[0] == 0) {
            break;
        }
    }
    fileClose(h);
    return result;
}

public int hwcap() {
    return auxv(16);
}

public int hwcap2() {
    return auxv(26);
}
'''
open(os.path.join(os.path.dirname(__file__), '..', 'lib', 'cpu.a'), 'w').write(src)
print('lib/cpu.a written')
