#!/usr/bin/env python3
"""Generates lib/gfxfont.a: antialiased bitmap fonts (DejaVu Sans, Sans Bold, Sans Mono at 13 px, Latin-1) as hex strings.

Per font:  byte ascent, byte line height, then for every code 32..255:
           advance, left bearing (signed), top (signed, pixels above the baseline), width, height,
           followed by width*height 4-bit coverage values, two per byte (first pixel in the high nibble), padded to a byte.
Usage: python3 docs/gen_font.py > lib/gfxfont.a      (DejaVu fonts are free software, see their license)
"""
from PIL import ImageFont, Image, ImageDraw
import sys

FONTS = [
    ("sans",     "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 13),
    ("sansBold", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 13),
    ("mono",     "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", 13),
]

def blob(path, size):
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    out = bytearray([asc, asc + desc])
    for code in range(32, 256):
        ch = chr(code)
        adv = int(round(f.getlength(ch)))
        bb = f.getbbox(ch, anchor="ls")
        w = max(0, bb[2] - bb[0]); h = max(0, bb[3] - bb[1])
        if code == 32 or code == 160 or w == 0 or h == 0:
            w = h = 0
        out += bytes([adv & 255, (bb[0] if w else 0) & 255, (-bb[1] if w else 0) & 255, w, h])
        if w:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-bb[0], -bb[1]), ch, font=f, fill=255, anchor="ls")
            px = im.load()
            vals = [px[x, y] * 15 // 255 for y in range(h) for x in range(w)]
            if len(vals) & 1: vals.append(0)
            for i in range(0, len(vals), 2):
                out.append((vals[i] << 4) | vals[i + 1])
    return out.hex()

print("// =============================================================================")
print("//  gfxfont - the fonts of the gfx module (generated by docs/gen_font.py, do not edit)")
print("//  DejaVu Sans, DejaVu Sans Bold and DejaVu Sans Mono, 13 pixels, antialiased, Latin-1.")
print("//  The DejaVu fonts are based on Bitstream Vera; they may be used and distributed freely.")
print("// =============================================================================")
print("module gfxfont;")
print()
for name, path, size in FONTS:
    h = blob(path, size)
    assert len(h) < 60000, (name, len(h))
    print("public char* %s() {" % name)
    print('    return "%s";' % h)
    print("}")
    print()
