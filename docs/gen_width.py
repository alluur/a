#!/usr/bin/env python3
"""Generates the character width tables of lib/tscreen.a from Python's unicodedata.

    python3 docs/gen_width.py          # rewrites the block between  BEGIN WIDTH TABLES  and  END WIDTH TABLES  in lib/tscreen.a

Zero width: categories Mn, Me, Cf (not U+00AD), and the Hangul medial vowels / final consonants U+1160..U+11FF.
Wide (two cells): East Asian Width W and F.  Everything else is one cell (ambiguous width counts as one).
"""
import sys
import unicodedata

def ranges(pred):
    out = []
    start = None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
            last = cp
        elif start is not None:
            out.append((start, last))
            start = None
    if start is not None:
        out.append((start, last))
    return out

def zero(cp):
    if cp == 0xAD or cp < 0x300:
        return False
    if 0x1160 <= cp <= 0x11FF:
        return True
    return unicodedata.category(chr(cp)) in ('Mn', 'Me', 'Cf')

def wide(cp):
    return cp >= 0x1100 and unicodedata.east_asian_width(chr(cp)) in ('W', 'F')

def table(name, rs):
    lines = []
    lo = ", ".join("0x%X" % a for a, b in rs)
    hi = ", ".join("0x%X" % b for a, b in rs)
    def wrap(txt):
        parts = txt.split(", ")
        res, cur = [], "   "
        for p in parts:
            if len(cur) + len(p) + 2 > 130:
                res.append(cur.rstrip())
                cur = "   "
            cur += " " + p + ","
        res.append(cur.rstrip(","))
        return "\n".join(res)
    return "int %sLo[%d] = {\n%s\n};\nint %sHi[%d] = {\n%s\n};\n" % (name, len(rs), wrap(lo), name, len(rs), wrap(hi)), len(rs)

z, nz = table("zeroW", ranges(zero))
w, nw = table("wideW", ranges(wide))
block = ("// BEGIN WIDTH TABLES (generated by docs/gen_width.py from Unicode %s)\nconst ZERO_RANGES = %d;\nconst WIDE_RANGES = %d;\n%s%s// END WIDTH TABLES\n"
         % (unicodedata.unidata_version, nz, nw, z, w))
path = sys.argv[1] if len(sys.argv) > 1 else "lib/tscreen.a"
src = open(path).read()
b = src.index("// BEGIN WIDTH TABLES")
e = src.index("// END WIDTH TABLES") + len("// END WIDTH TABLES\n")
open(path, "w").write(src[:b] + block + src[e:])
print("zero ranges:", nz, "wide ranges:", nw)
