#!/usr/bin/env python3
"""Makes lib/wwebpage.a (the page of the web display backend) from docs/web/index.html. Run after changing the page."""
import os
here = os.path.dirname(os.path.abspath(__file__))
html = open(os.path.join(here, 'web', 'index.html')).read()
lines = html.split('\n')
parts = []
for ln in lines:
    esc = ln.replace('\\', '\\\\').replace('"', '\\"')
    parts.append('    "%s\\n"' % esc)
src = '''// the page of the web display backend (generated by docs/gen_wweb_page.py from docs/web/index.html; do not edit)
module wwebpage;

public char* html() {
    return
%s;
}

// the page with the token put in (the token has only letters and digits)
public char* withToken(char* page, char* token) {
    int n = strlen(page);
    int tn = strlen(token);
    char* out = alloc(n + tn + 16);
    int o = 0;
    for (int i = 0; i < n; i++) {
        if (page[i] == '@' && page[i + 1] == 'T' && page[i + 2] == 'O' && page[i + 3] == 'K' && page[i + 4] == 'E' && page[i + 5] == 'N' && page[i + 6] == '@') {
            for (int k = 0; k < tn; k++) { out[o] = token[k]; o++; }
            i = i + 6;
        } else {
            out[o] = page[i];
            o++;
        }
    }
    out[o] = 0;
    return out;
}
''' % '\n'.join(parts)
open(os.path.join(here, '..', 'lib', 'wwebpage.a'), 'w').write(src)
print("lib/wwebpage.a: %d bytes of page" % len(html))
