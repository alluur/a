#!/usr/bin/env python3
"""Generates tests/t53_wchar.a and .out: wide character functions compared with Python's unicode data."""
import os, unicodedata, random
random.seed(53)
here = os.path.dirname(os.path.abspath(__file__))
tests = os.path.join(here, '..')
def simple(c, f):
    r = f(c)
    return ord(r) if len(r) == 1 else None
# characters the library claims to handle: ASCII, Latin-1, Latin Extended-A, Greek, Cyrillic, Armenian, fullwidth
ranges = [(0x20, 0x7E), (0xC0, 0x17F), (0x386, 0x3CE), (0x400, 0x45F), (0x531, 0x556), (0x561, 0x586), (0xFF21, 0xFF3A), (0xFF41, 0xFF5A)]
chars = [c for lo, hi in ranges for c in range(lo, hi + 1)]
skip = {0x130, 0x131, 0x138, 0x149, 0x17F, 0x1C5, 0xDF, 0xB5, 0x3C2, 0x3A2, 0x387, 0x38B, 0x38D, 0x3A2}
chars = [c for c in chars if c not in skip and unicodedata.category(chr(c)) != 'Cn']
a = ['// generated by tests/fuzz/gen_wchar_test.py',
     'import cwchar;', 'import clocale;', '', 'int main() {', '    int sum = 0;', '    int bad = 0;']
out = []
lines = []
for c in chars:
    u = simple(chr(c), str.upper)
    l = simple(chr(c), str.lower)
    if u is None or l is None:
        continue
    isup = chr(c).isupper() and l != c
    islo = chr(c).islower() and u != c
    ia = chr(c).isalpha()
    lines.append(f'    if (towupper({c}) != {u} || towlower({c}) != {l} || iswalpha({c}) != {1 if ia else 0} || iswupper({c}) != {1 if isup else 0} || iswlower({c}) != {1 if islo else 0}) {{ bad++; printf("wrong: %x\\n", {c}); }}')
a += lines
a += ['    printf("case mapping and classes: %d bad\\n", bad);']
out.append('case mapping and classes: 0 bad')
# strings
a += ['    int a[20]; int b[40]; int c[20];',
      '    mbstowcs(a, "Hello Wörld", 20);',
      '    printf("%d %d\\n", wcslen(a), wcscmp(a, a));',
      '    wcscpy(b, a); wcscat(b, a);',
      '    printf("%d\\n", wcslen(b));',
      '    mbstowcs(c, "Wör", 20);',
      '    int* p = wcsstr(a, c);',
      '    printf("%d %d\\n", p != null, (int) p == (int) &a[6]);',
      '    printf("%d %d\\n", wcschr(a, 0xF6) == &a[7], wcsrchr(a, \'l\') == &a[9]);',
      '    printf("%d %d\\n", wcsspn(a, c), wcscspn(a, c));',
      '    printf("%d %d %d\\n", wcsncmp(a, b, 5), wcscmp(c, a) > 0, wcscmp(a, c) < 0);',
      '    int text[20]; mbstowcs(text, " a,b;;c ", 20); int* save = null;',
      '    int count = 0; int* tk = wcstok(text, c, &save);',
      '    int dl[5]; mbstowcs(dl, ", ;", 5);',
      '    mbstowcs(text, " a,b;;c ", 20); tk = wcstok(text, dl, &save);',
      '    while (tk != null) { count++; tk = wcstok(null, dl, &save); }',
      '    printf("%d tokens\\n", count);',
      '    printf("%d %d %d %d\\n", wcwidth(\'a\'), wcwidth(0x65E5), wcwidth(0x301), wcwidth(10));',
      '    int w[5]; mbstowcs(w, "日本a", 5);',
      '    printf("%d\\n", wcswidth(w, 3));',
      '    printf("%d %d\\n", btowc(65), btowc(200));',
      '    printf("%s|%d\\n", setlocale(LC_ALL, "C"), setlocale(LC_ALL, "fr_FR.ISO-8859-1") == null);',
      '    printf("[%s] [%s]\\n", localeconv()->decimal_point, localeconv()->thousands_sep);',
      '    return 0;', '}']
out += ['11 0', '22', '1 1', '1 1', '5 0'.replace('5 0', '3 0'), '0 1 1', '3 tokens', '1 2 0 -1', '5', '65 -1', 'C|1', '[.] []']
# derive the lines that depend on the exact semantics by hand-checking:
# wcsspn("Hello Wörld","Wör") = 0 ('H' not in set); wcscspn(..) = 6 ('W' at index 6)
out[5] = '0 6'
# wcsncmp(a, b, 5) = 0 (b starts with a); wcscmp(c,a)>0: 'W' > 'H'; wcscmp(a,c)<0
out[6] = '0 1 1'
open(os.path.join(tests, 't53_wchar.a'), 'w').write('\n'.join(a) + '\n')
open(os.path.join(tests, 't53_wchar.out'), 'w').write('\n'.join(out) + '\n')
print(len(lines), 'characters checked')
