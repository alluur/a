#!/usr/bin/env python3
"""Generates tests/t43_ctime.a and .out: strftime / gmtime / localtime / mktime checked against Python's zoneinfo."""
import random, os, datetime, zoneinfo
random.seed(43)
here = os.path.dirname(os.path.abspath(__file__))
tests = os.path.join(here, '..')
zones = [
    ('UTC', 'UTC'),
    ('EET-2EEST,M3.5.0/3,M10.5.0/4', 'Europe/Helsinki'),
    ('EST5EDT,M3.2.0,M11.1.0', 'America/New_York'),
    ('AEST-10AEDT,M10.1.0,M4.1.0/3', 'Australia/Sydney'),
    ('<+0530>-5:30', 'Asia/Kolkata'),
    ('CET-1CEST,M3.5.0,M10.5.0/3', 'Europe/Paris'),
]
stamps = [0, 86399, 951782400, 1000000000, 1234567890, 1700000000, 1710000000, 1711846800, 1711850400, 1729990000,
          1730000000, 1730001000, 1760000000, 1893456000, 2000000000, 2147483647, 4102444800]
stamps += [random.randint(946684800, 1893456000) for _ in range(10)]
fmt = "%Y-%m-%d %H:%M:%S %a %b %j %U %V %u %y %e %I%p %Z %z"
a = ['// generated by tests/fuzz/gen_time_test.py',
     'import ctime;', 'import cstdio;', 'import cstdlib;', '',
     'int main() {', '    char b[200];', '    tm x;', '    int t;']
out = []
for tz, name in zones:
    a.append(f'    setenv("TZ", "{tz}", true);')
    a.append('    tzset();')
    a.append(f'    puts("== {name}");')
    z = zoneinfo.ZoneInfo(name)
    out.append(f'== {name}')
    for s in [x for x in stamps if x >= 1262304000 or name in ('UTC', 'Asia/Kolkata')]:   # the current DST rules are applied to all years
        a.append(f'    t = {s}; localtime_r(&t, &x); strftime(b, 200, "{fmt}", &x); puts(b);')
        d = datetime.datetime.fromtimestamp(s, z)
        txt = d.strftime(fmt)
        # Python %Z gives abbreviations like EET/EEST, but '+0530' style for Kolkata is IST in tzdata
        if name == 'Asia/Kolkata': txt = txt.replace('IST', '+0530')
        out.append(txt)
    # mktime round trips for a few local times
    a.append(f'    puts("-- mktime {name}");')
    out.append(f'-- mktime {name}')
    for (y, mo, dd, h) in [(2024, 1, 15, 12), (2024, 7, 15, 12), (2023, 3, 26, 12), (2024, 12, 31, 23), (2000, 2, 29, 0)]:
        a.append(f'    x.tm_year = {y-1900}; x.tm_mon = {mo-1}; x.tm_mday = {dd}; x.tm_hour = {h}; x.tm_min = 30; x.tm_sec = 15; x.tm_isdst = -1; x.tm_gmtoff = 0; x.tm_zone = null;')
        a.append('    t = mktime(&x); printlnInt(t);')
        dt = datetime.datetime(y, mo, dd, h, 30, 15, tzinfo=z)
        out.append(str(int(dt.timestamp())))
a += ['    // gmtime / timegm / normalization',
      '    t = 1700000000; tm* g = gmtime(&t); strftime(b, 200, "%c|%x|%X|%D|%R|%r|%G-W%V", g); puts(b);',
      '    puts(asctime(g));',
      '    x.tm_year = 124; x.tm_mon = 12; x.tm_mday = 40; x.tm_hour = 25; x.tm_min = 61; x.tm_sec = 61; printlnInt(timegm(&x));',
      '    strftime(b, 200, "%F %T", &x); puts(b);',
      '    tm y; memset((char*)&y, 0, sizeof(tm));',
      '    char* r = strptime("Fri, 15 Mar 2024 17:45:09 +0200", "%a, %d %b %Y %H:%M:%S %z", &y);',
      '    printlnInt(r != null); printlnInt(timegm(&y)); printlnInt(y.tm_gmtoff);',
      '    memset((char*)&y, 0, sizeof(tm));',
      '    r = strptime("03/15/24 05:45 PM", "%D %I:%M %p", &y);',
      '    printlnInt(r != null); strftime(b, 200, "%F %T", &y); puts(b);',
      '    printlnInt(strptime("nonsense", "%Y", &y) == null);',
      '    printlnInt(difftime(100, 40));',
      '    printlnInt(time(null) > 1700000000);',
      '    timespec ts; clock_gettime(CLOCK_REALTIME, &ts); printlnInt(ts.tv_sec > 1700000000);',
      '    printlnInt(clock() >= 0);',
      '    return 0;', '}']
g = datetime.datetime.fromtimestamp(1700000000, datetime.timezone.utc)
out.append(g.strftime("%a %b %e %H:%M:%S %Y") + "|" + g.strftime("%m/%d/%y") + "|" + g.strftime("%H:%M:%S") + "|" + g.strftime("%m/%d/%y") + "|" + g.strftime("%H:%M") + "|" + g.strftime("%I:%M:%S %p") + "|" + g.strftime("%G-W%V"))
out.append(g.strftime("%a %b %e %H:%M:%S %Y"))
out.append('')   # puts of the asctime string that ends with a newline
# timegm of the normalized date 2024-13-40 25:61:61
base = datetime.datetime(2025, 1, 1, tzinfo=datetime.timezone.utc) + datetime.timedelta(days=39, hours=25, minutes=61, seconds=61)
out.append(str(int(base.timestamp())))
out.append(base.strftime("%F %T"))
out.append('1')
out.append(str(int(datetime.datetime(2024, 3, 15, 17, 45, 9, tzinfo=datetime.timezone.utc).timestamp())))
out.append('7200')
out.append('1')
out.append('2024-03-15 17:45:00')
out += ['1', '60', '1', '1', '1']
open(os.path.join(tests, 't43_ctime.a'), 'w').write('\n'.join(a) + '\n')
open(os.path.join(tests, 't43_ctime.out'), 'w').write('\n'.join(out) + '\n')
print('ok', len(out), 'lines')
