#!/usr/bin/env python3
"""Generates tests/t54_ccomplex.a and .out: complex functions compared with Python's cmath (14 significant digits)."""
import cmath, os, random
random.seed(54)
here = os.path.dirname(os.path.abspath(__file__))
tests = os.path.join(here, '..')
zs = [(3.0, 4.0), (-4.0, 0.0), (0.0, 1.0), (1.0, 1.0), (-1.5, 2.5), (2.0, -3.0), (0.5, 0.25), (-0.25, -0.75), (10.0, 0.1), (0.0, 0.0), (2.0, 0.0), (-2.0, 0.0)]
funcs = [('cexp', cmath.exp), ('clog', cmath.log), ('csqrt', cmath.sqrt), ('csin', cmath.sin), ('ccos', cmath.cos), ('ctan', cmath.tan),
         ('csinh', cmath.sinh), ('ccosh', cmath.cosh), ('ctanh', cmath.tanh), ('casin', cmath.asin), ('cacos', cmath.acos), ('catan', cmath.atan)]
a = ['// generated by tests/fuzz/gen_complex_test.py',
     'import clib;', '',
     'void show(Complex* z) { printfd("%.12g %.12g\\n", creal(z), cimag(z)); }', '',
     'int main() {']
out = []
def f(x): return '%.12g' % x
for name, fn in funcs:
    for re, im in zs:
        z = complex(re, im)
        try:
            r = fn(z)
        except (ValueError, ZeroDivisionError, OverflowError):
            continue
        if name in ('clog',) and z == 0: continue
        if name in ('casin', 'cacos') and abs(z.real) > 5: continue     # ill-conditioned for this formula
        if name in ('catan', 'ctan', 'ctanh') and abs(z) < 1e-12 and False: continue
        a.append(f'    show({name}(cmplx(dlit("{re!r}"), dlit("{im!r}"))));')
        out.append(f(r.real) + ' ' + f(r.imag))
for (re, im), (re2, im2) in [((3, 4), (1, -2)), ((1.5, -0.5), (0.25, 2)), ((0, 1), (1, 0)), ((-2, 3), (4, 5))]:
    z, w = complex(re, im), complex(re2, im2)
    for name, r in [('cadd', z + w), ('csub', z - w), ('cmul', z * w), ('cdiv', z / w), ('cpow', z ** w)]:
        a.append(f'    show({name}(cmplx(dlit("{float(re)!r}"), dlit("{float(im)!r}")), cmplx(dlit("{float(re2)!r}"), dlit("{float(im2)!r}"))));')
        out.append(f(r.real) + ' ' + f(r.imag))
for re, im in [(3, 4), (-1, 0), (0, -2), (1e200, 1e200)]:
    z = complex(re, im)
    a.append(f'    {{ Complex* z = cmplx(dlit("{float(re)!r}"), dlit("{float(im)!r}")); printfd("%.12g %.12g\\n", cabs(z), carg(z)); show(conj(z)); show(cneg(z)); }}')
    import math
    out.append(f(abs(z)) + ' ' + f(cmath.phase(z)))
    out.append(f(z.conjugate().real) + ' ' + f(z.conjugate().imag))
    out.append(f(-z.real) + ' ' + f(-z.imag))
a += ['    return 0;', '}']
open(os.path.join(tests, 't54_ccomplex.a'), 'w').write('\n'.join(a) + '\n')
open(os.path.join(tests, 't54_ccomplex.out'), 'w').write('\n'.join(out) + '\n')
print(len(out), 'lines')
