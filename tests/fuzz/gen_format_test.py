#!/usr/bin/env python3
"""Generates tests/t39_vformat.a and .out: printf conversions of the standard library checked against the C library.
usage: gen_format_test.py   (needs gcc)"""
import random, subprocess, re, os, sys
random.seed(39)
here = os.path.dirname(os.path.abspath(__file__))
tests = os.path.join(here, '..')
vals = [0, 1, -1, 42, -42, 255, 4096, 123456789, -123456789, 2**63-1, -2**63, 2**32, 65535, 300, 70000, 7, 8, 100]
cases = []
for _ in range(220):
    fl = ''.join(random.sample(['-', '0', '+', ' ', '#'], random.randint(0, 3)))
    w = random.choice(['', '', '5', '10', '3', '12'])
    pr = random.choice(['', '', '.0', '.3', '.8', '.1'])
    conv = random.choice(['d', 'i', 'u', 'x', 'X', 'o', 'c', 's', 'd', 'x'])
    if conv in 'cs':
        fl = re.sub('[0+ #]', '', fl)
    if conv == 'c': pr = ''
    if conv in 'uxXo': fl = fl.replace('+', '').replace(' ', '')
    if conv in 'di': fl = fl.replace('#', '')
    pre = random.choice(['', 'l', 'll', 'z', '']) if conv not in 'cs' else ''
    v = random.choice(vals)
    if conv == 'c': v = random.choice([65, 97, 48, 33])
    sv = random.choice(['hello', '', 'abcdefghijklmnop', 'x'])
    cases.append((f"<%{fl}{w}{pr}{pre}{conv}>", conv, v, sv))
a = ['// generated by tests/fuzz/gen_format_test.py - printf conversions compared with the C library',
     'int main() {', '    char b[256];', '    int args[1];']
c = ['#include <stdio.h>', 'int main(){', 'char b[256];']
for f, conv, v, sv in cases:
    if conv == 's':
        a.append(f'    args[0] = (int)"{sv}"; vformat(b, 256, "{f}\\n", args, 1); print(b);')
        c.append(f'snprintf(b,256,"{f}\\n","{sv}"); fputs(b,stdout);')
    else:
        vs = f'({v})' if v != -2**63 else '(-9223372036854775807-1)'
        a.append(f'    args[0] = {vs}; vformat(b, 256, "{f}\\n", args, 1); print(b);')
        cf = re.sub(r'(ll|l|z)(?=[diuxXoc]>)', '', f)
        ct = 'long long' if conv in 'di' else ('int' if conv == 'c' else 'unsigned long long')
        if conv != 'c': cf = cf[:-2] + 'll' + conv + '>'
        ce = str(v) if conv == 'c' else (f'({ct}){v}LL' if v != -2**63 else f'({ct})(-9223372036854775807LL-1)')
        c.append(f'snprintf(b,256,"{cf}\\n",{ce}); fputs(b,stdout);')
# the dynamic width / precision, several values and truncation
a += ['    int v6[6];', '    v6[0] = 6; v6[1] = 42; v6[2] = 6; v6[3] = 42; v6[4] = 3; v6[5] = (int)"abcdef";',
      '    vformat(b, 256, "[%*d] [%-*d] [%.*s]\\n", v6, 6); print(b);',
      '    v6[0] = 6; v6[1] = 42; v6[2] = 3;',
      '    printlnInt(vformat(b, 8, "%d-%d-%d", v6, 3)); println(b);',
      '    return 0;', '}']
c += ['{ long long v4[4]; snprintf(b,256,"[%*lld] [%-*lld] [%.*s]\\n",6,42LL,6,42LL,3,"abcdef"); fputs(b,stdout);',
      'printf("%d\\n", snprintf(b,8,"%lld-%lld-%lld",6LL,42LL,3LL)); puts(b); }', 'return 0;}']
open(os.path.join(tests, 't39_vformat.a'), 'w').write('\n'.join(a) + '\n')
open('/tmp/_gen_fmt.c', 'w').write('\n'.join(c))
subprocess.check_call(['gcc', '-w', '-o', '/tmp/_gen_fmt', '/tmp/_gen_fmt.c'])
open(os.path.join(tests, 't39_vformat.out'), 'w').write(subprocess.run(['/tmp/_gen_fmt'], capture_output=True, text=True).stdout)
print('written', len(cases), 'cases')
