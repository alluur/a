#!/usr/bin/env python3
"""Generates tests/t45_cmath_arith.a/.out and tests/t46_cmath_funcs.a/.out.
Expected values come from hardware doubles (arithmetic) and from mpmath at high precision, rounded once (functions),
so the tests check that the library is correctly rounded.  Needs: pip install mpmath"""
import random, os, math, struct
import mpmath
mpmath.mp.prec = 300
random.seed(45)
here = os.path.dirname(os.path.abspath(__file__))
tests = os.path.join(here, '..')

def g(x):
    """C's %.17g"""
    return '%.17g' % x

def lit(x):
    if x != x: return 'NAN'
    if x == float('inf'): return 'INFINITY'
    if x == float('-inf'): return 'NEG_INFINITY'
    return 'dlit("%s")' % repr(x)

def rounded(f, *xs):
    r = f(*[mpmath.mpf(x) for x in xs])
    if isinstance(r, mpmath.mpc): return float('nan')
    try: return float(r)
    except OverflowError: return float('inf') if r > 0 else float('-inf')

