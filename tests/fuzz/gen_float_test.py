#!/usr/bin/env python3
"""Generates tests/t47_cfloat.a and .out: printf of doubles (checked against the C library), strtod and dtostr
(checked against Python's float and repr).  Needs gcc."""
import random, subprocess, os, struct, math
random.seed(47)
here = os.path.dirname(os.path.abspath(__file__))
tests = os.path.join(here, '..')
def bits(x): return struct.unpack('<q', struct.pack('<d', x))[0]
def rv():
    t = random.random()
    if t < 0.2: return random.choice([0.0, -0.0, 1.0, -1.0, 0.5, 2.5, 1e22, 1e-5, 123456.789, 0.1, 5e-324, 1.7976931348623157e308, 2.2250738585072014e-308, float('inf'), float('-inf'), 9.9999995, 0.000123456, 999999.5, 1e15, 1e16, 1e17, 0.3, 100.0])
    if t < 0.5: return random.uniform(-1000, 1000)
    if t < 0.7: return random.uniform(-1, 1) * 10 ** random.randint(-30, 30)
    if t < 0.8: return random.randint(-10**6, 10**6) / random.choice([1, 2, 4, 8, 10, 100, 1000])
    return random.uniform(-1, 1) * 10 ** random.randint(-320, 308)
a = ['// generated by tests/fuzz/gen_float_test.py',
     'import cfloat;', '', 'int main() {', '    char b[1500];', '    int args[2];']
c = ['#include <stdio.h>', 'int main(){', 'char b[1500];']
out = []
specs = []
for _ in range(150):
    fl = ''.join(random.sample(['-', '0', '+', ' ', '#'], random.randint(0, 3)))
    w = random.choice(['', '', '8', '15', '25'])
    p = random.choice(['', '', '.0', '.1', '.3', '.6', '.10', '.17', '.20', '.30'])
    cv = random.choice('fFeEgGaA')
    if cv in 'aA': p = random.choice(['', '', '.0', '.1', '.5', '.13'])
    specs.append((f"%{fl}{w}{p}{cv}", rv()))
for f, v in specs:
    a.append(f'    args[0] = {bits(v)}; vformatd(b, 1500, "<{f}>\\n", args, 1); print(b);')
    if v != v: lit = 'NAN'
    elif v == float('inf'): lit = '(1.0/0.0)'
    elif v == float('-inf'): lit = '(-1.0/0.0)'
    else: lit = repr(v)
    c.append(f'snprintf(b,1500,"<{f}>\\n",{lit}); fputs(b,stdout);')
c.append('return 0;}')
open('/tmp/_gen_flt.c', 'w').write('\n'.join(c))
subprocess.check_call(['gcc', '-w', '-o', '/tmp/_gen_flt', '/tmp/_gen_flt.c', '-lm'])
out += subprocess.run(['/tmp/_gen_flt'], capture_output=True, text=True).stdout.splitlines()
# mixed integer and double values in one format, widths from arguments
a += ['    printfd("%d items, %5.1f%% done, %s=%8.3e [%*.*f]\\n", 7, dlit("42.25"), "x", dlit("12345.6789"), 9, 2, dlit("3.14159"));',
      '    printfd("%x %c %-6d|%+.2f|% .3g\\n", 255, 65, 42, dlit("2.0"), dlit("0.000123456"));',
      '    char s[20];',
      '    printlnInt(snprintfd(s, 8, "%f", dlit("1234.5"))); println(s);',
      '    printlnInt(sprintfd(s, "%.2f", dlit("2.675"))); println(s);']
out += ['7 items,  42.2% done, x=1.235e+04 [     3.14]', 'ff A 42    |+2.00| 0.000123', '11', '1234.50', '4', '2.67']
# strtod
strs = ['0', '-0', '1', '3.14159', '  42', '+7.5e2', '.5', '5.', '1e5', '1E-5', '1e400', '-1e400', '1e-400', '4.9e-324', '2.4703282292062327e-324',
        '2.4703282292062328e-324', '1.7976931348623157e308', '1.7976931348623159e308', '0.1', '0.2', '0.30000000000000004', '123456789012345678901234567890',
        '0.000000000000000000000000000001', '9007199254740993', '9007199254740992.5', '1.00000000000000011102230246251565404236316680908203125',
        '1.00000000000000011102230246251565404236316680908203126', '0x1p0', '0x1.8p3', '-0x.8p1', '0x1p-1074', '0x1.fffffffffffffp1023', 'inf', '-Infinity', 'nan',
        'abc', '1e', '1e+', '12abc', '0x', '2.5e3x']
for s in strs:
    a.append(f'    {{ char* e; int v = strtod("{s}", &e); printfd("%s -> ", "{s}"); println(dtostr(v)); }}'.replace('printfd("%s -> ", "'+s+'")','print("'+s+' -> ")'))
    # expected: Python float() for the numeric prefix
    import re
    t = s.strip()
    m = re.match(r'^[+-]?(inf(inity)?|nan|0x[0-9a-f]*\.?[0-9a-f]*(p[+-]?\d+)?|(\d+\.?\d*|\.\d+)(e[+-]?\d+)?)', t, re.I)
    if not m or m.group(0) in ('0x', ''):
        # no conversion, or "0x" alone converts the "0"
        if t.lower().startswith('0x') and m is None: val = 0.0
        else: val = 0.0
        txt = '0.0'
        if t.lower().startswith('0x'): txt = '0.0'
    else:
        g = m.group(0)
        try:
            if 'x' in g.lower(): val = float.fromhex(g)
            else: val = float(g)
        except OverflowError: val = float('inf')
        if g.lower().endswith('e') or g.lower().endswith('e+') : pass
        if val != val: txt = 'nan'
        elif val == float('inf'): txt = 'inf'
        elif val == float('-inf'): txt = '-inf'
        else: txt = repr(val)
    out.append(f'{s} -> {txt}')
# dtostr
vals = [random.choice([0.1, 0.3, 1e22, 1e16, 1e15, 123456789012345678.0, 1e-4, 1e-5, 5e-324, 1.7976931348623157e308, 100.0, 0.5, 2.5e-5, -0.0, 0.0,
                       float('inf'), float('-inf'), float('nan')]) if random.random() < 0.4 else rv() for _ in range(60)]
for v in vals:
    a.append(f'    println(dtostr({bits(v)}));')
    out.append('nan' if v != v else ('inf' if v == float('inf') else ('-inf' if v == float('-inf') else repr(v))))
a += ['    println(dtostr(itod(100)));', '    return 0;', '}']
out.append('100.0')
open(os.path.join(tests, 't47_cfloat.a'), 'w').write('\n'.join(a) + '\n')
open(os.path.join(tests, 't47_cfloat.out'), 'w').write('\n'.join(out) + '\n')
print('written', len(out), 'lines')
