#!/usr/bin/env python3
"""Writes tests/t304_switch_big.a and .out (and the error test t304_err_switch_toomany): switch statements with 1000 text labels (many of them with the same hash) and 1000
integer labels (numbers beyond 32 bits, negative numbers, ranges), checked against the table they were made from.
Run:  python3 tests/gen/gen_switch_big.py     (Python is only needed to regenerate the test, not to run it)"""
import random, os

random.seed(30401)
here = os.path.dirname(os.path.abspath(__file__))
tests = os.path.join(here, "..")
alpha = "abcdefghijklmnopqrstuvwxyz"


def fnv(s, h=0x811C9DC5):
    """the hash of switch on text: FNV-1a over the bytes, 32 bits (sw_hash in src/switch.asm, __swhash in lib/std.a)"""
    for b in s.encode():
        h ^= b
        h = (h * 0x01000193) & 0xFFFFFFFF
    return h


def pairs_from(state, count):
    """pairs of 6 letter words that reach the same hash when the hash starts in 'state' (birthday search)"""
    by = {}
    rng = random.Random(state)
    for _ in range(700000):
        w = "".join(rng.choice(alpha) for _ in range(6))
        by.setdefault(fnv(w, state), set()).add(w)
    return [sorted(v)[:2] for v in by.values() if len(v) >= 2][:count]


# ---- text labels: pairs, a group of four and a group of eight words with one hash each, then random words
pairs = pairs_from(0x811C9DC5, 14)
assert len(pairs) >= 13
groups = pairs[:12]
# if a and b have the same hash, a+x and b+x have it too, for every x: pairs that collide from the state reached after the previous
# pair multiply into groups of 4 and 8 words
q = pairs_from(fnv(pairs[12][0]), 1)[0]
g4 = [a + b for a in pairs[12] for b in q]
r = pairs_from(fnv(g4[0]), 1)[0]
g8 = [a + b for a in g4 for b in r]
groups += [g4, g8]
words = []
misses = ["", "zzzzzzzzzz", "ABC", "x y", "a" * 40]
for gi, g in enumerate(groups):
    assert len({fnv(w) for w in g}) == 1
    for k, w in enumerate(g):
        if k == len(g) - 1 and gi % 2 == 0:
            misses.append(w)            # a word with the hash of labels that is itself not a label
        else:
            words.append(w)
seen = set(words) | set(misses)
while len(words) < 1000:
    n = random.randint(1, 9)
    w = "".join(random.choice(alpha) for _ in range(n))
    if w not in seen:
        seen.add(w)
        words.append(w)
random.shuffle(words)
assert len(words) == 1000
cases = "".join('        case "%s": return %d;\n' % (w, i + 1) for i, w in enumerate(words))

# ---- integer labels: random numbers (also beyond 32 bits and negative), 20 of them are ranges
ent = []
while len(ent) < 980:
    v = random.choice([random.randint(-10**6, 10**6), random.randint(-2**40, 2**40), random.randint(2**31 - 100, 2**31 + 100)])
    if any(abs(v - e[0]) < 60 or abs(v - e[1]) < 60 for e in ent):
        continue
    ent.append((v, v))
for _ in range(20):
    while True:
        lo = random.randint(-2**36, 2**36)
        hi = lo + random.randint(5, 40)
        if all(hi + 60 < e[0] or lo - 60 > e[1] for e in ent):
            ent.append((lo, hi))
            break
random.shuffle(ent)
icases = ""
for i, (lo, hi) in enumerate(ent):
    icases += ("        case %d: return %d;\n" % (lo, i + 1)) if lo == hi else ("        case %d..%d: return %d;\n" % (lo, hi, i + 1))


def expected_int(v):
    for i, (lo, hi) in enumerate(ent):
        if lo <= v <= hi:
            return i + 1
    return 0


probes = []
for lo, hi in ent[:200]:
    probes += [lo, hi, lo - 1, hi + 1, (lo + hi) // 2]
probes += [0, 1, -1, 2**62, -2**62]
exp_hits = sum(1 for p in probes if expected_int(p))
exp_sum = sum(expected_int(p) for p in probes)

wl = ",\n".join('    "%s"' % w for w in words)
ml = ",\n".join('    "%s"' % w for w in misses)
pl = ",\n".join("    %d" % p for p in probes)
src = f"""// switch with 1000 text labels (twelve pairs, a group of four and a group of eight labels have the same hash, and some words that are not
// labels share a hash with labels) and with 1000 integer labels (numbers beyond 32 bits, negative numbers, twenty ranges).
// Generated by tests/gen/gen_switch_big.py.
char* words[1000] = {{
{wl}
}};
char* misses[{len(misses)}] = {{
{ml}
}};
int probes[{len(probes)}] = {{
{pl}
}};

int lookup(char* s) {{
    switch (s) {{
{cases}        default: return 0;
    }}
}}

int ilookup(int v) {{
    switch (v) {{
{icases}        default: return 0;
    }}
}}

int main() {{
    int bad = 0;
    int sum = 0;
    foreach (int i, char* w in words) {{
        int r = lookup(w);
        if (r != i + 1) {{ bad++; }}
        sum += r;
    }}
    printf("words: %d wrong, sum %d\\n", bad, sum);
    int hits = 0;
    foreach (char* m in misses) {{ if (lookup(m) != 0) {{ hits++; }} }}
    printf("misses that matched: %d, null: %d\\n", hits, lookup(null));
    int ihits = 0;
    int isum = 0;
    foreach (int p in probes) {{
        int r = ilookup(p);
        if (r != 0) {{ ihits++; isum += r; }}
    }}
    printf("numbers: %d hits, sum %d\\n", ihits, isum);
    return 0;
}}
"""
open(os.path.join(tests, "t304_switch_big.a"), "w").write(src)
out = "words: 0 wrong, sum %d\nmisses that matched: 0, null: 0\nnumbers: %d hits, sum %d\n" % (sum(range(1, 1001)), exp_hits, exp_sum)
open(os.path.join(tests, "t304_switch_big.out"), "w").write(out)
# a switch with more labels than the compiler takes (4096): the error test
many = "".join("        case %d: return %d;\n" % (i, i) for i in range(4097))
open(os.path.join(tests, "t304_err_switch_toomany.a"), "w").write("int f(int n) {\n    switch (n) {\n" + many + "    }\n    return 0;\n}\nint main() { return f(1); }\n")
open(os.path.join(tests, "t304_err_switch_toomany.err"), "w").write("too many case labels")
print("wrote t304_switch_big:", len(words), "words,", len(ent), "numbers,", len(misses), "misses,", len(probes), "probes")
