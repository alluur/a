#!/usr/bin/env python3
"""Generates tests/t331_interp_int_float.a and its expected output.

The test formats integers with a floating point letter in an interpolated string ($"{n:.2f}", {n:e}, ...). The program never
mentions the type double and has no floating point literal, so the soft-float runtime is not loaded: the integer is converted
to the bits of a double with integer arithmetic (__i2f / __u2f in lib/std.a). Python's float(int) is correctly rounded (ties to
even), so the expected text of every line is a reference for that conversion and for the exact formatter.

Usage:  tests/gen/gen_interp_int_test.py        (from the repository root)
"""
import random

rng = random.Random(331)
M63 = 1 << 63
M64 = 1 << 64

signed = [0, 1, -1, 2, 3, -3, 7, 10, 255, 256, 65535, 123456789, -123456789, 2**31 - 1, -2**31, 2**32, 2**52, 2**53, 2**53 + 1,
          2**53 + 2, 2**53 + 3, -(2**53) - 1, 2**54 + 1, 2**54 + 2, 2**54 + 3, 2**60 + 255, 2**62, 2**62 + 1, 2**63 - 1,
          2**63 - 513, 2**63 - 1024, -2**63, -2**63 + 1, -2**63 + 512, 999999999999999999, 4611686018427387903,
          9007199254740993, 9007199254740995, 12345678901234567]
for _ in range(25):
    bits = rng.choice([8, 20, 40, 53, 54, 55, 58, 62, 63])
    v = rng.getrandbits(bits)
    signed.append(v if rng.random() < 0.5 else -v)

unsigned = [0, 1, 2**53 + 1, 2**63 - 1, 2**63, 2**63 + 1, 2**63 + 1024, 2**63 + 1025, 2**63 + 2048, 2**63 + 3072, 2**63 + 3073,
            2**64 - 1, 2**64 - 1024, 2**64 - 1025, 2**64 - 2048, 2**64 - 513, 14000000000000000000, 18000000000000000000,
            9223372036854775809, 9223372036854777857]
for _ in range(15):
    unsigned.append(rng.getrandbits(64) | M63)

def lit(v):
    if v == -M63:
        return '-9223372036854775807 - 1'
    return str(v)

def ulit(v):
    return str(v)          # the lexer takes a decimal literal up to 2^64 - 1

out = []
src = []
src.append('// an integer printed with a floating point letter in an interpolated string: converted with integer arithmetic (this file has no')
src.append('// floating point type and no floating point literal, so the soft-float runtime is not even loaded)')
src.append('// (generated by tests/gen/gen_interp_int_test.py, the expected text is Python\'s %-formatting of float(n))')
src.append('int main() {')
src.append('    int s[%d] = {%s};' % (len(signed), ', '.join(lit(v) for v in signed)))
src.append('    for (int i = 0; i < %d; i++) {' % len(signed))
src.append('        int v = s[i];')
src.append('        println($"{v:.0f} {v:e} {v:.17g} {v:+.2f} {v:30.1f}|");')
src.append('    }')
src.append('    uint64 u[%d] = {%s};' % (len(unsigned), ', '.join(ulit(v) for v in unsigned)))
src.append('    for (int i = 0; i < %d; i++) {' % len(unsigned))
src.append('        uint64 w = u[i];')
src.append('        println($"{w} {w:.0f} {w:E} {w:.17g} {w:G}");')
src.append('    }')
# other integer types and the small things
src.append('    char c = 65;')
src.append('    bool b = true;')
src.append('    int8 i8 = -5;')
src.append('    uint32 u32 = 4000000000;')
src.append('    println($"{c:.1f} {b:.1f} {i8:.2f} {u32:.0f} {3:v} {-7:v} {100000:v}");')
src.append('    println($"{12:.3e} {12:8.2f}|{12:-8.2f}|{12:08.2f}|{-12:+08.1f}|");')
src.append('    return 0;')
src.append('}')

def fmt_e(x):
    return '%e' % x

for v in signed:
    f = float(v)
    out.append('%.0f %e %.17g %+.2f %30.1f|' % (f, f, f, f, f))
for v in unsigned:
    f = float(v)
    out.append('%d %.0f %E %.17g %G' % (v, f, f, f, f))
out.append('65.0 1.0 -5.00 4000000000 3 -7 100000')
out.append('1.200e+01    12.00|12.00   |00012.00|-00012.0|')

open('tests/t331_interp_int_float.a', 'w').write('\n'.join(src) + '\n')
open('tests/t331_interp_int_float.out', 'w').write('\n'.join(out) + '\n')
