#!/usr/bin/env python3
"""Makes tests/t128_tls.a: a TLS 1.3 client and server of lib/tls.a talk to each other in memory (no sockets, so it runs on
every target). The certificates and keys are made here, with Python's `cryptography` package, and valid until 2100.
Run: python3 tests/gen/gen_tls_test.py     (then run the program once and keep its output as tests/t128_tls.out after checking it)"""
import datetime, os, random
from cryptography import x509 as cx
from cryptography.x509.oid import NameOID
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import rsa, ec

here = os.path.dirname(os.path.abspath(__file__))
def nm(cn): return cx.Name([cx.NameAttribute(NameOID.COMMON_NAME, cn)])
def mk(sub, key, iss, ikey, ca, sans=None):
    b = cx.CertificateBuilder().subject_name(nm(sub)).issuer_name(nm(iss)).public_key(key.public_key()).serial_number(random.getrandbits(63) + 1)
    b = b.not_valid_before(datetime.datetime(2020, 1, 1, tzinfo=datetime.timezone.utc)).not_valid_after(datetime.datetime(2100, 1, 1, tzinfo=datetime.timezone.utc))
    b = b.add_extension(cx.BasicConstraints(ca=ca, path_length=None), critical=True)
    if sans: b = b.add_extension(cx.SubjectAlternativeName([cx.DNSName(s) for s in sans]), critical=False)
    return b.sign(ikey, hashes.SHA256())
def pem(c): return c.public_bytes(serialization.Encoding.PEM).decode()
def kpem(k, fmt): return k.private_bytes(serialization.Encoding.PEM, fmt, serialization.NoEncryption()).decode()
def lit(t): return '"' + t.replace('\n', '\\n') + '"'
P8 = serialization.PrivateFormat.PKCS8; P1 = serialization.PrivateFormat.TraditionalOpenSSL

cak = ec.generate_private_key(ec.SECP256R1()); ca = mk("Test CA", cak, "Test CA", cak, True)
otherk = ec.generate_private_key(ec.SECP256R1()); other = mk("Other CA", otherk, "Other CA", otherk, True)
rk = rsa.generate_private_key(65537, 2048); rc = mk("server.test", rk, "Test CA", cak, False, ["server.test"])
ek = ec.generate_private_key(ec.SECP256R1()); ecert = mk("server.test", ek, "Test CA", cak, False, ["server.test"])
e3 = ec.generate_private_key(ec.SECP384R1()); e3cert = mk("server.test", e3, "Test CA", cak, False, ["server.test"])

consts = [("CA_PEM", pem(ca)), ("OTHER_CA_PEM", pem(other)),
          ("RSA_CERT", pem(rc)), ("RSA_KEY8", kpem(rk, P8)), ("RSA_KEY1", kpem(rk, P1)),
          ("EC_CERT", pem(ecert)), ("EC_KEY8", kpem(ek, P8)), ("EC_KEY1", kpem(ek, P1)),
          ("EC384_CERT", pem(e3cert)), ("EC384_KEY1", kpem(e3, P1))]

body = open(os.path.join(here, 'tls_test_body.a')).read()
src = "// generated by tests/gen/gen_tls_test.py (certificates are test material, valid until 2100): do not edit\n"
src += "import tls;\nimport x509;\nimport hash;\nimport secure;\nimport cstring;\n\n"
for name, text in consts:
    src += "char* %s = %s;\n" % (name, lit(text))
src += "\n" + body
open(os.path.join(here, '..', 't128_tls.a'), 'w').write(src)
print("t128_tls.a written")
