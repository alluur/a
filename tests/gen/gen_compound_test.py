#!/usr/bin/env python3
"""Writes tests/t307_compound_ops.a and .out: every compound assignment (+= -= *= /= %= &= |= ^= <<= >>=) on variables, struct fields,
array elements and pointer targets of every integer type, checked against a Python model of the language's rules: the operation is
done on 64 bit values (a uint64 target makes / % >> unsigned) and the result is cut to the width of the target when it is stored.
Run:  python3 tests/gen/gen_compound_test.py     (Python is only needed to regenerate the test, not to run it)"""
import os, random

random.seed(307)
here = os.path.dirname(os.path.abspath(__file__))
tests = os.path.join(here, "..")

TYPES = {  # name: (bits, signed)
    "int": (64, True), "char": (8, False), "int8": (8, True), "int16": (16, True), "uint16": (16, False),
    "int32": (32, True), "uint32": (32, False), "uint64": (64, False), "size_t": (64, False),
}
OPS = ["+", "-", "*", "/", "%", "&", "|", "^", "<<", ">>"]


def trunc(v, bits, signed):
    v &= (1 << bits) - 1
    if signed and v >> (bits - 1):
        v -= 1 << bits
    return v


def cdiv(a, b):
    q = abs(a) // abs(b)
    return q if (a < 0) == (b < 0) else -q


def model(op, l, r, bits, signed):
    """the 64 bit operation, then the result is cut to the target type"""
    u64 = bits == 64 and not signed
    L, R = (l & (2**64 - 1), r & (2**64 - 1)) if u64 else (l, r)
    if op == "+": v = L + R
    elif op == "-": v = L - R
    elif op == "*": v = L * R
    elif op == "/": v = L // R if u64 else cdiv(L, R)
    elif op == "%": v = L % R if u64 else L - R * cdiv(L, R)
    elif op == "&": v = L & R
    elif op == "|": v = L | R
    elif op == "^": v = L ^ R
    elif op == "<<": v = L << R
    elif op == ">>": v = L >> R          # Python's >> is arithmetic for negative numbers, like the language's
    return trunc(v, bits, signed)


def lefts_for(bits, signed):
    cands = [0, 1, 5, 100, 127, 200, 255, 1000, 30000, 65535, 70000, 2**31 - 1, 2**31, 3000000000, 2**32 + 5, 2**40 + 7, 2**62, 2**63 + 9]
    if signed:
        cands += [-1, -7, -100, -128, -129, -32768, -70000, -2**31, -2**40 - 3, -2**63]
    out = []
    for c in cands:
        t = trunc(c, bits, signed)
        if t not in out:
            out.append(t)
    return out


def literal(v):
    if v == -2**63:
        return "(-9223372036854775807 - 1)"
    return str(v) if v >= 0 else "(%d)" % v


funcs, mains, outs = [], [], []
for tname, (bits, signed) in TYPES.items():
    u64 = bits == 64 and not signed
    show = "showU" if u64 else "show"
    lefts = lefts_for(bits, signed)
    random.shuffle(lefts)
    fn = [f"struct Holder_{tname} {{ {tname} x; }}", f"void run_{tname}() {{"]
    rows = []
    for oi, op in enumerate(OPS):
        row = []
        for k in range(4):
            l = lefts[(k * 3 + oi) % len(lefts)]
            if op in ("<<", ">>"):
                r = random.choice([0, 1, 3, 7, 8, 13, 31, 33])
            elif op in ("/", "%"):
                r = random.choice([1, 2, 3, 7, 10, 100, 255, 1000] + ([] if u64 else [-3, -10]))
            else:
                r = random.choice([0, 1, 2, 5, 77, 255, 256, 1000, 65536, 2**33 + 1] + ([] if u64 else [-1, -300]))
            res = model(op, l, r, bits, signed)
            row.append(res)
            if k == 0:
                code = f"{tname} v = {literal(l)}; v {op}= {literal(r)}; {show}(v);"
            elif k == 1:
                code = f"Holder_{tname} h; h.x = {literal(l)}; h.x {op}= {literal(r)}; {show}(h.x);"
            elif k == 2:
                code = f"{tname} a[3]; a[0] = 1; a[1] = {literal(l)}; a[2] = 2; int i = 0; a[++i] {op}= {literal(r)}; {show}(a[1]); show(i);"
                row.append(1)
            else:
                code = f"{tname} v = {literal(l)}; {tname}* p = &v; *p {op}= {literal(r)}; {show}(v);"
            fn.append(f"    {{ {code} }}")
        fn.append('    println("");')
        rows.append(" ".join("%d" % x for x in row) + " ")
    fn.append("}")
    funcs.append("\n".join(fn))
    mains.append(f'    println("-- {tname}"); run_{tname}();')
    outs.append(f"-- {tname}\n" + "\n".join(rows))

src = """// compound assignments (+= -= *= /= %= &= |= ^= <<= >>=) on every integer type: variables, struct fields, array elements (the index
// expression runs once) and pointer targets. Generated by tests/gen/gen_compound_test.py from a model of the language rules.
void show(int v) { printInt(v); print(" "); }
void showU(uint64 v) { printf("%u ", v); }

""" + "\n\n".join(funcs) + "\n\nint main() {\n" + "\n".join(mains) + "\n    return 0;\n}\n"
open(os.path.join(tests, "t307_compound_ops.a"), "w").write(src)
open(os.path.join(tests, "t307_compound_ops.out"), "w").write("\n".join(outs) + "\n")
print("wrote t307_compound_ops")
