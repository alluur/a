#!/usr/bin/env python3
"""Makes tests/t129_gui_https.a: gnet.Fetch talks https to a TLS server run by the test itself (lib/tls.a, non-blocking, polled
in the event loop). Certificates for 127.0.0.1 are made here with Python's `cryptography` package and valid until 2100.
Run: python3 tests/gen/gen_https_test.py"""
import datetime, ipaddress, os, random
from cryptography import x509 as cx
from cryptography.x509.oid import NameOID
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import rsa, ec

here = os.path.dirname(os.path.abspath(__file__))
def nm(cn): return cx.Name([cx.NameAttribute(NameOID.COMMON_NAME, cn)])
def mk(sub, key, iss, ikey, ca, ip=None):
    b = cx.CertificateBuilder().subject_name(nm(sub)).issuer_name(nm(iss)).public_key(key.public_key()).serial_number(random.getrandbits(63) + 1)
    b = b.not_valid_before(datetime.datetime(2020, 1, 1, tzinfo=datetime.timezone.utc)).not_valid_after(datetime.datetime(2100, 1, 1, tzinfo=datetime.timezone.utc))
    b = b.add_extension(cx.BasicConstraints(ca=ca, path_length=None), critical=True)
    if ip: b = b.add_extension(cx.SubjectAlternativeName([cx.IPAddress(ipaddress.ip_address(ip))]), critical=False)
    return b.sign(ikey, hashes.SHA256())
def pem(c): return c.public_bytes(serialization.Encoding.PEM).decode()
def kpem(k): return k.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()).decode()
def lit(t): return '"' + t.replace('\n', '\\n') + '"'
cak = ec.generate_private_key(ec.SECP256R1()); ca = mk("Test CA", cak, "Test CA", cak, True)
sk = ec.generate_private_key(ec.SECP256R1()); sc = mk("127.0.0.1", sk, "Test CA", cak, False, "127.0.0.1")
otherk = ec.generate_private_key(ec.SECP256R1()); other = mk("Other CA", otherk, "Other CA", otherk, True)
fk = ec.generate_private_key(ec.SECP256R1()); fc = mk("127.0.0.1", fk, "Other CA", otherk, False, "127.0.0.1")
consts = [("CA_PEM", pem(ca)), ("SERVER_CERT", pem(sc)), ("SERVER_KEY", kpem(sk)), ("STRANGER_CERT", pem(fc)), ("STRANGER_KEY", kpem(fk))]
src = "// generated by tests/gen/gen_https_test.py (test certificates, valid until 2100): do not edit\n"
for n, t in consts: src += "char* %s = %s;\n" % (n, lit(t))
src += "\n" + open(os.path.join(here, 'https_test_body.a')).read()
open(os.path.join(here, '..', 't129_gui_https.a'), 'w').write(src)
print("t129_gui_https.a written")
